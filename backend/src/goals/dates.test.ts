import { describe, expect, it } from "vitest";
import {
  APP_TIME_ZONE,
  parseIsoDate,
  todayInAppZone,
  toIsoDate,
} from "./dates.js";

describe("parseIsoDate", () => {
  it("зөв өдрийг задална", () => {
    expect(parseIsoDate("2026-12-31")).toEqual({
      year: 2026,
      month: 12,
      day: 31,
    });
  });

  it("хэлбэр буруу бол null", () => {
    for (const value of [
      "2026-12-3", // өдөр нь нэг цифр
      "2026-1-31", // сар нь нэг цифр
      "26-12-31", // жил нь хоёр цифр
      "2026/12/31", // өөр тусгаарлагч
      "2026-12-31T00:00:00Z", // цаг нэмсэн
      "өнөөдөр",
      "",
    ]) {
      expect(parseIsoDate(value), value).toBeNull();
    }
  });

  /**
   * Хуанлид байхгүй өдрүүд.
   *
   * Зөвхөн регексээр шалгавал эдгээр бүгд "зөв" болж, ӨС рүү орохдоо
   * чимээгүйхэн өөр өдөр болж хувирна. `new Date(Date.UTC(2026,1,30))`
   * нь 2026-03-02 болдог — хэрэглэгч тохируулсан хугацаа нь өөр өдөр
   * болчихсон байна гэдэг.
   */
  it("байхгүй өдрийг татгалзана", () => {
    for (const value of [
      "2026-02-30", // хоёрдугаар сард 30 байхгүй
      "2026-02-29", // 2026 нь үсрэх жил биш
      "2026-13-01", // 13-р сар
      "2026-00-10", // 0-р сар
      "2026-12-00", // 0-р өдөр
      "2026-12-32",
      "2026-04-31", // дөрөвдүгээр сар 30 хоногтой
    ]) {
      expect(parseIsoDate(value), value).toBeNull();
    }
  });

  it("үсрэх жилийн хоёрдугаар сарын 29-ийг зөвшөөрнө", () => {
    expect(parseIsoDate("2028-02-29")).not.toBeNull();
  });
});

describe("toIsoDate", () => {
  it("нэг цифрт тэг нөхнө", () => {
    expect(toIsoDate({ year: 2026, month: 2, day: 9 })).toBe("2026-02-09");
  });

  /**
   * Тэг нөхөх нь гоо сайхны асуудал биш.
   *
   * Бүх мөр ижил урттай байж л ТЭМДЭГТЭЭР харьцуулахад хуанлийн
   * дараалал гарна. Шалгагч нь үүн дээр бүрэн найддаг.
   */
  it("тэмдэгтийн дараалал нь хуанлийн дараалал болно", () => {
    const sorted = ["2026-02-09", "2026-02-10", "2026-03-01", "2027-01-01"];

    expect([...sorted].sort()).toEqual(sorted);
  });
});

describe("todayInAppZone", () => {
  it("ISO хэлбэрээр буцаана", () => {
    expect(todayInAppZone()).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });

  /**
   * ЦАГИЙН БҮСИЙН ГОЛ ТЕСТ.
   *
   * UTC-ээр 2026-11-03-ын 17:00 нь Улаанбаатарт аль хэдийн
   * 2026-11-04-ийн 01:00. Серверийн UTC өдрөөр шийдвэл хэрэглэгч
   * өөрийнхөө "өнөөдөр"-ийг тохируулахад "өнгөрсөн өдөр" гэж
   * татгалзуулах байв.
   */
  it("Улаанбаатарын өдрөөр тоолно, UTC-ээр биш", () => {
    const evening = new Date("2026-11-03T17:00:00Z");

    expect(evening.toISOString().slice(0, 10)).toBe("2026-11-03");
    expect(todayInAppZone(evening)).toBe("2026-11-04");
  });

  it("шөнө дундын дараа ч тухайн өдрөө хэлнэ", () => {
    // UB = UTC+8, тул UTC 16:00 нь UB-ийн шөнө дунд.
    expect(todayInAppZone(new Date("2026-11-03T16:00:00Z"))).toBe("2026-11-04");
    expect(todayInAppZone(new Date("2026-11-03T15:59:59Z"))).toBe("2026-11-03");
  });

  it("бүсийн нэр нь Монголын цагийн бүс", () => {
    expect(APP_TIME_ZONE).toBe("Asia/Ulaanbaatar");
  });
});
