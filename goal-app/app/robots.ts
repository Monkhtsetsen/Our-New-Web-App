import type { MetadataRoute } from "next";

/**
 * /robots.txt-ийг үүсгэнэ.
 *
 * Next.js энэ файлыг таньж, build хийх үедээ статик robots.txt болгоно.
 * public/robots.txt гэж гараар бичихээс дээр: төрөл шалгагддаг,
 * орчноос хамааруулж өөрчлөх боломжтой.
 *
 * ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
 * АНХААР: robots.txt бол ХАМГААЛАЛТ БИШ.
 *
 * Энэ нь хайлтын системд тавьсан ЭЕЛДЭГ ХҮСЭЛТ. Дагах эсэх нь тэдний
 * сайн дурын хэрэг бөгөөс хортой бот огт тоохгүй. Үүнээс гадна
 * robots.txt нь хэн ч уншиж болдог ил файл учраас /admin зам байдгийг
 * зарлаж өгдөг.
 *
 * Админ хуудсыг жинхэнээр хамгаалах цорын ганц арга нь СЕРВЕР ДЭЭР
 * эрх шалгах явдал: нэвтэрсэн эсэх, тухайн хэрэглэгчийн role нь
 * "admin" эсэх. Тэр ажлыг `proxy.ts` ба `app/admin/page.tsx` хоёр
 * хийнэ — энэ файл нь зөвхөн хайлтын системд хандсан хүсэлт.
 * ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        // robots.txt-д зам нь угтвараар тааруулагддаг тул "/admin" нь
        // "/admin", "/admin/users", "/admin/..." бүгдийг хамарна.
        disallow: "/admin",
      },
    ],
  };
}
