// sum.test.js — ЭХЛЭЭД ТЕСТЛЭЛИЙГ БИЧИХ (TDD-ийн "Улаан" шат)
const sum = require('./sum');

test('1 + 2 = 3 гарах ёстой', () => {
  expect(sum(1, 2)).toBe(3);
});

// --- Алхам 4: шинэ шаардлага — тоон бус өгөгдөл өгвөл алдаа заана ---
//
// ТЭМДЭГЛЭЛ: Лабораторийн зааварт энэ тест
//   expect(() => sum(1, 2)).toThrow('Тоо оруулах шаардлагатай!');
// гэж хэвлэгдсэн байсан. Гэвч 1 ба 2 хоёулаа тоо тул функц алдаа шидэх
// ёсгүй — энэ хэлбэрээр бичвэл тест хэзээ ч ногоон болохгүй.
// Зааврын PDF-ээс хашилтын тэмдэг алга болсон нь илэрхий (мөн адил
// require(./sum), typeof a !== number гэж хэвлэгдсэн) тул эх хувилбар нь
// sum(1, '2') байсан гэж үзэж, тоон бус аргументыг үнэхээр дамжуулав.
test('Тоо биш өгөгдөл өгвөл алдаа заана', () => {
  expect(() => sum(1, '2')).toThrow('Тоо оруулах шаардлагатай!');
});

// --- 3 дахь давталт: рефактор хийх явцад илэрсэн сул тал ---
//
// JavaScript дээр typeof NaN === 'number' бөгөөд typeof Infinity === 'number'.
// Өөрөөр хэлбэл одоогийн шалгалт эдгээрийг "тоо" гэж үзэн нэвтрүүлнэ. Ингэснээр
// sum(NaN, 1) нь алдаа шидэхгүйгээр NaN-г чимээгүй буцаана.
//
// Манай төсөлд XP, Level, Streak-ийн тооцоололд NaN нэг удаа орвол хэрэглэгчийн
// өгөгдөл бүхэлдээ гажиж, буцаан засахад хэцүү болно. Тиймээс үүнийг засна.
//
// ЧУХАЛ: энэ нь ШИНЭ ЗАН ТӨЛӨВ тул рефактор биш. TDD-ийн дүрмээр эхлээд тест
// бичиж улаан болгоод, дараа нь кодыг засна.
test('NaN эсвэл Infinity өгвөл алдаа заана', () => {
  expect(() => sum(NaN, 1)).toThrow('Тоо оруулах шаардлагатай!');
  expect(() => sum(1, Infinity)).toThrow('Тоо оруулах шаардлагатай!');
});
